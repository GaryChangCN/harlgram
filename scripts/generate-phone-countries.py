#!/usr/bin/env python3
"""Generate offline dialing data from pinned upstream XML; no third-party Python modules."""
import argparse
import hashlib
import json
from pathlib import Path
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / '.local/third_party/phone-country-data'
SOURCES = {
    'PhoneNumberMetadata.xml': ('https://raw.githubusercontent.com/google/libphonenumber/v9.0.18/resources/PhoneNumberMetadata.xml', '85d29280b344f66e11c9499c38585f7eef1e274524fe376ab8f1d204903efa75'),
    'zh.xml': ('https://raw.githubusercontent.com/unicode-org/cldr/release-47/common/main/zh.xml', '97fea2cfdb7bfe59a4e0ce712ca2e6ccba67ef211957296f60365c9f84b24d52'),
    'en.xml': ('https://raw.githubusercontent.com/unicode-org/cldr/release-47/common/main/en.xml', 'cdb3d09f4d5cd206616a57cc8a8cb54c458c6678758c59b8b817125fe2dfb147'),
    'libphonenumber-LICENSE': ('https://raw.githubusercontent.com/google/libphonenumber/v9.0.18/LICENSE', 'a6cba85bc92e0cff7a450b1d873c0eaa2e9fc96bf472df0247a26bec77bf3ff9'),
    'cldr-LICENSE': ('https://raw.githubusercontent.com/unicode-org/cldr/release-47/LICENSE', 'b4c0ae8ef04f7059f96ce5bbe0467f9fe6f6d81bbe13517701dfeb961fb4d0b6'),
}


def source(name, offline):
    url, digest = SOURCES[name]
    path = CACHE / name
    if not path.exists():
        if offline:
            raise RuntimeError(f'离线缓存缺少 {name}；先执行一次不带 --offline 的命令。')
        data = urllib.request.urlopen(url, timeout=30).read()
        if hashlib.sha256(data).hexdigest() != digest:
            raise RuntimeError(f'{name} 下载校验失败，未写入缓存。')
        CACHE.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise RuntimeError(f'{name} 缓存校验失败；请核查来源，不自动覆盖。')
    return data


def names(data):
    return {entry.attrib['type']: entry.text for entry in ET.fromstring(data).findall('./localeDisplayNames/territories/territory') if 'alt' not in entry.attrib}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--offline', action='store_true', help='Only use already verified local source cache')
    parser.add_argument('--check', action='store_true', help='Check checked-in output without changing it')
    args = parser.parse_args()
    data = {name: source(name, args.offline) for name in SOURCES}
    zh, en = names(data['zh.xml']), names(data['en.xml'])
    countries, primary = [], []
    for item in ET.fromstring(data['PhoneNumberMetadata.xml']).findall('./territories/territory'):
        iso = item.attrib['id']
        if iso == '001':
            continue  # Global services have calling codes but are not countries/regions.
        if iso not in zh or iso not in en:
            raise RuntimeError(f'固定 CLDR 数据缺少 {iso} 的名称')
        countries.append({'iso': iso, 'name': zh[iso], 'englishName': en[iso], 'dialCode': '+' + item.attrib['countryCode']})
        if item.attrib.get('mainCountryForCode') == 'true':
            primary.append(iso)
    countries.sort(key=lambda item: item['iso'])
    if len(countries) != 245 or len({item['iso'] for item in countries}) != len(countries):
        raise RuntimeError('地区覆盖或唯一性检查失败')
    header = '''// Generated by scripts/generate-phone-countries.py; do not edit dialing codes by hand.
// Dialing metadata: libphonenumber v9.0.18, Copyright (C) 2009 The Libphonenumber Authors, Apache-2.0.
// Localized names: Unicode CLDR release-47, Unicode License V3. See docs/PHONE_COUNTRY_DATA.md.
export interface PhoneCountry { iso: string; name: string; englishName: string; dialCode: string; }

export const PHONE_COUNTRIES: PhoneCountry[] = [
'''
    output = header + ''.join('  ' + json.dumps(item, ensure_ascii=False) + ',\n' for item in countries) + '];\n\n'
    output += 'export const PHONE_MAIN_COUNTRY_ISOS: string[] = ' + json.dumps(sorted(primary)) + ';\n'
    targets = {
        ROOT / 'entry/src/main/ets/data/PhoneCountries.ts': output.encode(),
        ROOT / 'entry/src/main/resources/rawfile/licenses/Libphonenumber.txt': data['libphonenumber-LICENSE'],
        ROOT / 'entry/src/main/resources/rawfile/licenses/Unicode-CLDR.txt': data['cldr-LICENSE'],
    }
    for path, content in targets.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                raise RuntimeError(f'生成文件未同步：{path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(f'{"已核验" if args.check else "已生成"} {len(countries)} 个国家和地区；源码 SHA-256 全部通过。')


if __name__ == '__main__':
    main()
